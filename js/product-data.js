function findProduct(id) {
  return PRODUCTS.find((p) => p.id === id) || null;
}
function getCategory(number) {
  return CATEGORIES.find((c) => c.number === Number(number)) || null;
}
function getProductsForCategory(number) {
  const n = Number(number);
  return PRODUCTS.filter((p) => p.categoryNumber === n);
}
function getRelatedProducts(product, limit = 4) {
  if (!product) return [];
  return PRODUCTS.filter((p) => p.categoryNumber === product.categoryNumber && p.id !== product.id).slice(0, limit);
}
function formatPrice(product) {
  return priceHtml(product.price, product.salePrice);
}
function getStockStatus(p) {
  return p.inStock === false ? "out" : "in";
}
function stockStatusHtml(p) {
  return getStockStatus(p) === "out"
    ? `<span class="stock-text out-of-stock">Out of Stock</span>`
    : `<span class="stock-text in-stock">In Stock</span>`;
}
function escapeHtml(str) {
  if (str == null) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

async function loadLiveCatalog() {
  try {
    const res = await fetch("/.netlify/functions/get-catalog");
    if (!res.ok) return;
    const data = await res.json();
    if (Array.isArray(data.categories) && data.categories.length) {
      CATEGORIES.length = 0;
      CATEGORIES.push(...data.categories);
    }
    if (Array.isArray(data.products) && data.products.length) {
      // Keep the built-in detail copy (specs, features, lab results,
      // photo, wording) for any field the database has nothing saved for,
      // so a product edited in /admin.html never loses its detail page.
      // Products that only exist in the database (added in admin) are
      // used as-is, and products deleted in admin stay gone.
      const builtIn = {};
      PRODUCTS.forEach((p) => { builtIn[p.id] = p; });
      const keepIfEmpty = ["tagline", "description", "image", "specs", "features", "qcIntro", "qcCompound", "qcAssayResult", "qcStatus"];
      const merged = data.products.map((live) => {
        const base = builtIn[live.id];
        if (!base) return live;
        const out = { ...base, ...live };
        keepIfEmpty.forEach((k) => { if (live[k] == null || live[k] === "") out[k] = base[k]; });
        return out;
      });
      PRODUCTS.length = 0;
      PRODUCTS.push(...merged);
    }
    if (data.settings) {
      window.LIVE_SETTINGS = data.settings;
      if (typeof applyLiveSettings === "function") applyLiveSettings(data.settings);
    }
  } catch (err) {
    // Offline, backend not connected, or function not deployed.
  }
}
window.catalogReadyPromise = loadLiveCatalog();
